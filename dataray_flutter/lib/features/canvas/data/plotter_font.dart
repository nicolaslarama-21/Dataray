    [0x63, 0x14, 0x08, 0x14, 0x63],
    [0x07, 0x08, 0x70, 0x08, 0x07],
    [0x61, 0x51, 0x49, 0x45, 0x43],
    [0x3e, 0x51, 0x49, 0x45, 0x3e],
    [0x00, 0x42, 0x7f, 0x40, 0x00],
    [0x42, 0x61, 0x51, 0x49, 0x46],
    [0x21, 0x41, 0x45, 0x4b, 0x31],
    [0x18, 0x14, 0x12, 0x7f, 0x10],
    [0x27, 0x45, 0x45, 0x45, 0x39],
    [0x3c, 0x4a, 0x49, 0x49, 0x30],
    [0x01, 0x71, 0x09, 0x05, 0x03],
    [0x36, 0x49, 0x49, 0x49, 0x36],
    [0x06, 0x49, 0x49, 0x29, 0x1e],
  ];
  static bool pixel(String char, int x, int y) {
    final code = char.codeUnitAt(0);
    final index = code >= 65 && code <= 90
        ? code - 65
        : code >= 48 && code <= 57
            ? 26 + code - 48
            : -1;
    if (index >= 0) return columns[index][x] & (1 << y) != 0;
    if (char == '.') return x == 2 && y == 6;
    if (char == ',') return x == 2 && y == 5 || x == 1 && y == 6;
    if (char == '-') return y == 3 && x >= 1 && x <= 3;
    if (char == '!') return x == 2 && (y < 4 || y == 6);
    if (char == '?') return [2, 1, 0x51, 9, 6][x] & (1 << y) != 0;
    return false;
  }

  static List<TracePoint> preview(String text) {
    final chars = text.toUpperCase().split('').take(64).toList();
    final rows = (chars.length + 7) ~/ 8;
    final height = (rows * 9 - 3).clamp(6, 1000);
    return List.unmodifiable([
      for (var i = 0; i < chars.length; i++)
        for (var x = 0; x < 5; x++)
          for (var y = 0; y < 7; y++)
            if (pixel(chars[i], x, y))
              TracePoint(((i % 8) * 6 + x) / 46, ((i ~/ 8) * 9 + y) / height,
                  dot: true),
    ]);
  }
}
